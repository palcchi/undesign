/**
 * Loader for the FigCraft-derived WASM engine (built by `npm run build:wasm`
 * into `src/wasm/pkg/`). The engine owns its own document; the boundary
 * contract is JSON strings, documented in `rust/src/lib.rs`.
 *
 * Loading is lazy and fallible: when the WASM package is missing or fails to
 * instantiate, callers get an EngineLoadError with an actionable message
 * instead of an unhandled rejection.
 */

export interface WasmEngineInstance {
  execute(cmd: string, paramsJson: string): string;
  undo(): boolean;
  redo(): boolean;
  /** "undo_depth,redo_depth". */
  undoDepth(): string;
  /** JSON array of selected node ids. */
  selection(): string;
  setSelection(idsJson: string): void;
  /** JSON document summary; see rust/src/lib.rs. */
  docInfo(): string;
  /** Active page subtree as JSON (depth levels of children). */
  describePage(depth: number): string;
  /** One node as JSON; throws when the id names no node. */
  describeNode(id: number): string;
  /** Click-hit the active page in page coords: `{"id":…}` or `null`. */
  hitTest(x: number, y: number): string;
  exportPageSvg(): string;
  save(): string;
  load(json: string): void;
}

interface WasmGlueModule {
  // The generated glue resolves to InitOutput; the loader only awaits it.
  default: () => Promise<unknown>;
  WasmEngine: new () => WasmEngineInstance;
}

export class EngineLoadError extends Error {
  constructor(message: string) {
    super(message);
    this.name = 'EngineLoadError';
  }
}

function loadFailureHint(e: unknown): string {
  const msg = e instanceof Error ? e.message : String(e);
  if (/failed to fetch|load failed|404|not found/i.test(msg)) {
    return `${msg} — the engine was not built; run "npm run build:wasm" and reload.`;
  }
  return msg;
}

async function importGlue(): Promise<WasmGlueModule> {
  // The glue is generated by wasm-pack and may not exist before the first
  // `npm run build:wasm`; a missing file rejects here and becomes an
  // EngineLoadError below, never a build break.
  // @ts-ignore: generated file, absent until the WASM build runs.
  const mod = await import('./pkg/undesign_wasm.js');
  return mod as WasmGlueModule;
}

export interface LoadedEngine {
  engine: WasmEngineInstance;
  /** Spawn additional independent sessions (File → New reuses the module). */
  createSession: () => WasmEngineInstance;
}

/**
 * Instantiate the WASM engine. Pass `importer` in tests to simulate a
 * missing or broken module without touching the real build output.
 */
export async function loadWasmEngine(
  importer: () => Promise<WasmGlueModule> = importGlue,
): Promise<LoadedEngine> {
  let mod: WasmGlueModule;
  try {
    mod = await importer();
  } catch (e) {
    throw new EngineLoadError(`Could not load the engine module: ${loadFailureHint(e)}`);
  }
  try {
    await mod.default();
  } catch (e) {
    throw new EngineLoadError(`Could not start the engine: ${loadFailureHint(e)}`);
  }
  try {
    return { engine: new mod.WasmEngine(), createSession: () => new mod.WasmEngine() };
  } catch (e) {
    throw new EngineLoadError(`Could not create the engine session: ${loadFailureHint(e)}`);
  }
}

/** Parse the "u,r" depth encoding; garbage yields [0, 0]. */
export function parseUndoDepth(raw: string): [number, number] {
  const [u, r] = raw.split(',').map((n) => Number(n));
  return [Number.isFinite(u) && u >= 0 ? Math.floor(u) : 0, Number.isFinite(r) && r >= 0 ? Math.floor(r) : 0];
}
